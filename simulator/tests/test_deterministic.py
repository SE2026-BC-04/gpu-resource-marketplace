"""Frozen, independent Phase 1E/Phase 2E V1-V4 contract vectors.

Expected values are copied from the approved reference specification rather
than generated by the implementation under test.
"""
from __future__ import annotations

import hashlib
import json
from uuid import UUID

import pytest

from gpu_marketplace_simulator.deterministic import (
    ALGORITHM_VERSION,
    SimulationInput,
    _derive_seed_value,
    _hash_domain,
    canonical_input_bytes,
    simulate,
)

WORKER = UUID("11111111-1111-4111-8111-111111111111")
LISTING = UUID("22222222-2222-4222-8222-222222222222")
JOB = UUID("33333333-3333-4333-8333-333333333333")
JOB_REJECTION = UUID("33333333-3333-4333-8333-000000000c02")

# Duration, Job, seed, bucket, work units, outcome, failure, frozen digest.
VECTORS = (
    (60, JOB, 3035342533442321017, 47, 522303, "SUCCESS", None,
     "sha256:a643e286d2b4b89606cd8559078a8765cd73c7d602eec4f1ca4bba2ca732ef0c"),
    (2, JOB, 8887054454783268118, 86, 634290, "FAILED", "WORKER_FAULT",
     "sha256:9baaaaa338423c75753ecbd00da615a1f88a006eeb0a512d432635664754b7bf"),
    (1, JOB, 2063102514678027846, 97, 490818, "FAILED", "JOB_FAULT",
     "sha256:f1c9d8e371bd4e6876a73b2414c285c6362fe01bca4d8d432169f4d484b3d749"),
    (60, JOB_REJECTION, 2240287873181493078, 16, 562456, "SUCCESS", None,
     "sha256:ad2212d44fef948b303afb1e5d5d8e9435eeab64f6701c54cafc3c6f3fd77aa7"),
)


def _input(duration: int, job: UUID = JOB) -> SimulationInput:
    return SimulationInput(
        job_id=job,
        listing_id=LISTING,
        worker_id=WORKER,
        requested_gpu_count=2,
        duration_seconds=duration,
    )


@pytest.mark.parametrize(
    ("duration", "job", "seed", "bucket", "work_units", "outcome", "failure", "digest"),
    VECTORS,
    ids=("V1-success", "V2-worker-fault", "V3-job-fault", "V4-rejection"),
)
def test_exact_frozen_vectors(
    duration: int, job: UUID, seed: int, bucket: int, work_units: int,
    outcome: str, failure: str | None, digest: str,
) -> None:
    data = _input(duration, job)
    result = simulate(data)

    assert ALGORITHM_VERSION == "demo-v1-public1"
    assert _derive_seed_value(data) == seed
    assert set(result.output) == {
        "duration_seconds", "failure_reason", "job_id", "listing_id",
        "outcome", "requested_gpu_count", "schema_version", "work_units",
        "workload_profile",
    }
    assert result.output == {
        "duration_seconds": duration,
        "failure_reason": failure,
        "job_id": str(job),
        "listing_id": str(LISTING),
        "outcome": outcome,
        "requested_gpu_count": 2,
        "schema_version": "demo-v1",
        "work_units": work_units,
        "workload_profile": "demo-v1",
    }
    assert result.result_digest == digest
    assert int.from_bytes(
        _hash_domain("outcome", 0, canonical_input_bytes(data))[:4], "big"
    ) % 100 == bucket
    # Independent verification of the digest against the approved output.
    expected_bytes = json.dumps(
        result.output, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")
    assert result.result_digest == "sha256:" + hashlib.sha256(expected_bytes).hexdigest()
    assert simulate(data) == result


def test_v1_canonical_input_is_exact_seven_key_reference() -> None:
    assert canonical_input_bytes(_input(60)) == (
        b'{"algorithm_version":"demo-v1-public1","duration_seconds":60,'
        b'"job_id":"33333333-3333-4333-8333-333333333333",'
        b'"listing_id":"22222222-2222-4222-8222-222222222222",'
        b'"requested_gpu_count":2,'
        b'"worker_id":"11111111-1111-4111-8111-111111111111",'
        b'"workload_profile":"demo-v1"}'
    )


def test_v4_rejection_sampling_uses_counter_one() -> None:
    raw = canonical_input_bytes(_input(60, JOB_REJECTION))
    first = int.from_bytes(_hash_domain("work_units", 0, raw)[:4], "big")
    second = int.from_bytes(_hash_domain("work_units", 1, raw)[:4], "big")
    assert first == 4294735637
    assert first >= 4_294_000_000
    assert second == 316562456
    assert second < 4_294_000_000
    assert simulate(_input(60, JOB_REJECTION)).output["work_units"] == second % 1_000_000


@pytest.mark.parametrize("field", ("job_id", "listing_id", "worker_id"))
def test_rejects_non_v4_identity(field: str) -> None:
    kwargs = dict(
        job_id=JOB, listing_id=LISTING, worker_id=WORKER,
        requested_gpu_count=2, duration_seconds=60,
    )
    kwargs[field] = UUID("11111111-1111-1111-8111-111111111111")
    with pytest.raises(ValueError, match="UUIDv4"):
        SimulationInput(**kwargs)


@pytest.mark.parametrize("field", ("requested_gpu_count", "duration_seconds"))
@pytest.mark.parametrize("invalid", (0, -1, 2**31, True, 1.5))
def test_rejects_invalid_integer_inputs(field: str, invalid: object) -> None:
    kwargs = dict(
        job_id=JOB, listing_id=LISTING, worker_id=WORKER,
        requested_gpu_count=2, duration_seconds=60,
    )
    kwargs[field] = invalid
    with pytest.raises(ValueError, match="signed-32-bit"):
        SimulationInput(**kwargs)


def test_rejects_unapproved_profile() -> None:
    with pytest.raises(ValueError, match="frozen demo-v1"):
        SimulationInput(
            job_id=JOB, listing_id=LISTING, worker_id=WORKER,
            requested_gpu_count=2, duration_seconds=60,
            workload_profile="demo-v2",
        )


@pytest.mark.parametrize("domain", ("unknown", "signed-result", ""))
def test_rejects_unapproved_hash_domain(domain: str) -> None:
    with pytest.raises(ValueError, match="unknown deterministic domain"):
        _hash_domain(domain, 0, canonical_input_bytes(_input(60)))


@pytest.mark.parametrize("counter", (-1, 2**32))
def test_rejects_counter_outside_uint32(counter: int) -> None:
    with pytest.raises(ValueError, match="outside UINT32"):
        _hash_domain("work_units", counter, canonical_input_bytes(_input(60)))


def test_output_is_detached_and_has_no_protected_reference_fields() -> None:
    a = simulate(_input(60))
    assert "seed_value" not in a.output
    assert "expected_digest" not in a.output
    assert "algorithm_version" not in a.output
    a.output["work_units"] = -1
    assert simulate(_input(60)).output["work_units"] == 522303
