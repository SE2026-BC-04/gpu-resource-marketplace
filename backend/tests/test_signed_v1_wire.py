@pytest.mark.parametrize("where", ["value", "key", "signature", "raw"])
def test_errors_never_echo_input(where) -> None:
    marker = "SECRET-MARKER-9f3a"
    if where == "value":
        raw = envelope_bytes(payload_with(job_id=marker))
    elif where == "key":
        raw = envelope_bytes(payload_with(**{marker: "x"}))
    elif where == "signature":
        raw = envelope_bytes(signature=marker)
    else:
        raw = marker.encode() + b"{"
    with pytest.raises(SignedV1WireError) as caught:
        parse_signed_envelope_v1(raw, max_bytes=PROPOSED_MAX_ENVELOPE_BYTES, max_depth=PROPOSED_MAX_NESTING_DEPTH)
    error = caught.value
    for text in (str(error), repr(error), repr(error.args), str(error.code)):
        assert marker not in text
    assert error.__cause__ is None
    assert error.__suppress_context__ is True


def test_error_is_a_value_error_with_a_stable_code_and_no_secrets_in_the_message() -> None:
    error = reject(b"{", WireErrorCode.MALFORMED_JSON)
    assert isinstance(error, ValueError)
    assert error.code.value == "MALFORMED_JSON"


# --- purity -------------------------------------------------------------------------


def test_module_imports_only_the_standard_library_and_rfc8785() -> None:
    tree = ast.parse(Path(wire_v1.__file__).read_text(encoding="utf-8"))
    roots = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            roots.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            roots.add(node.module.split(".")[0])
    allowed = {
        "__future__", "base64", "binascii", "dataclasses", "enum", "json", "re", "rfc8785", "typing", "datetime",
    }
    assert roots <= allowed, roots - allowed
    for banned in ("sqlalchemy", "psycopg", "fastapi", "httpx", "starlette", "time", "os", "logging", "random", "socket"):
        assert banned not in roots
