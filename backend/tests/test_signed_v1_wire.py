SIGNING_PREFIX = b"GPU-MARKETPLACE:SIGNED-RESULT:V1\n"

# ADR-004 section 3.4 public vector.
VECTOR_PAYLOAD = {
    "schema_version": "1",
    "result_id": "11111111-1111-4111-8111-111111111111",
    "job_id": "22222222-2222-4222-8222-222222222222",
    "attempt_id": "33333333-3333-4333-8333-333333333333",
    "worker_id": "44444444-4444-4444-8444-444444444444",
    "listing_id": "55555555-5555-4555-8555-555555555555",
    "outcome": "SUCCESS",
    "failure_reason": None,
    "result_digest": "sha256:09f2515ffa28dcb5b292d813bab12b968bcad73292ef2a98d63ca3ed77e2af38",
    "finished_at": "2026-10-18T08:00:00.000000Z",
    "key_id": "66666666-6666-4666-8666-666666666666",
}
VECTOR_SIGNATURE = (
    "903mx-bzZtTjVuZR_r6BfuZt-ghu4IG_Tknq1_wkFTv4SFE91BJ_1uDXwt-AGU71cki9s-xzwU8QdRQOWQT2AQ"
)
VECTOR_SIGNED_BYTES_SHA256 = "152b4b0f1dd8c4a1ed96524247dc682892a0cfa661fbc396d32af5bfdcd16728"
PAYLOAD_FIELDS = tuple(VECTOR_PAYLOAD)
UUID_FIELDS = ("result_id", "job_id", "attempt_id", "worker_id", "listing_id", "key_id")


def envelope_bytes(payload=None, *, signature=VECTOR_SIGNATURE, encoding=SIGNATURE_ENCODING, **extra) -> bytes:
    outer = {
        "payload": VECTOR_PAYLOAD if payload is None else payload,
        "signature": signature,
        "signature_encoding": encoding,
    }
    outer.update(extra)
    return json.dumps(outer, separators=(",", ":")).encode("utf-8")


def payload_with(**changes) -> dict:
    payload = copy.deepcopy(VECTOR_PAYLOAD)
    payload.update(changes)
    return payload


def reject(
    raw,
    code: WireErrorCode,
    *,
    max_bytes: int = PROPOSED_MAX_ENVELOPE_BYTES,
    max_depth: int = PROPOSED_MAX_NESTING_DEPTH,
) -> SignedV1WireError:
    with pytest.raises(SignedV1WireError) as caught:
        parse_signed_envelope_v1(raw, max_bytes=max_bytes, max_depth=max_depth)
    assert caught.value.code is code
    return caught.value


# --- vector, byte retention and canonical parts -------------------------------------


def test_adr004_vector_parses_and_extracts_exact_signed_parts() -> None:
    raw = envelope_bytes()
    parsed = parse_signed_envelope_v1(raw, max_bytes=PROPOSED_MAX_ENVELOPE_BYTES, max_depth=PROPOSED_MAX_NESTING_DEPTH)
    assert parsed.raw_envelope is raw
    assert parsed.envelope.signature == VECTOR_SIGNATURE
    assert parsed.envelope.signature_encoding == "base64url-no-padding"
    assert dataclasses.asdict(parsed.envelope.payload) == VECTOR_PAYLOAD

    payload_jcs_raw, signature_raw = extract_signed_parts_v1(raw, max_bytes=PROPOSED_MAX_ENVELOPE_BYTES, max_depth=PROPOSED_MAX_NESTING_DEPTH)
    assert type(payload_jcs_raw) is bytes and type(signature_raw) is bytes
    assert len(payload_jcs_raw) == 500
    assert not payload_jcs_raw.startswith(b"\xef\xbb\xbf") and not payload_jcs_raw.endswith(b"\n")
    assert not payload_jcs_raw.startswith(SIGNING_PREFIX)
    assert len(SIGNING_PREFIX + payload_jcs_raw) == 533
    assert hashlib.sha256(SIGNING_PREFIX + payload_jcs_raw).hexdigest() == VECTOR_SIGNED_BYTES_SHA256
    assert len(signature_raw) == 64
    assert base64.urlsafe_b64encode(signature_raw).rstrip(b"=").decode("ascii") == VECTOR_SIGNATURE


def test_pretty_printed_and_reordered_input_keeps_bytes_but_yields_the_same_jcs() -> None:
    reference = extract_signed_parts_v1(envelope_bytes(), max_bytes=PROPOSED_MAX_ENVELOPE_BYTES, max_depth=PROPOSED_MAX_NESTING_DEPTH)
    reordered_payload = dict(reversed(list(VECTOR_PAYLOAD.items())))
    reordered = json.dumps(
        {"signature_encoding": SIGNATURE_ENCODING, "signature": VECTOR_SIGNATURE, "payload": reordered_payload},
        indent=3,
    ).encode("utf-8") + b"\n"
    parsed = parse_signed_envelope_v1(reordered, max_bytes=PROPOSED_MAX_ENVELOPE_BYTES, max_depth=PROPOSED_MAX_NESTING_DEPTH)
    assert parsed.raw_envelope is reordered
    assert extract_signed_parts_v1(reordered, max_bytes=PROPOSED_MAX_ENVELOPE_BYTES, max_depth=PROPOSED_MAX_NESTING_DEPTH) == reference


