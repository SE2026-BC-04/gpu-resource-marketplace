def _nested(depth: int) -> bytes:
    """An envelope-shaped object whose extra member nests ``depth`` levels counting the root."""
    extra = b"[" * (depth - 1) + b"]" * (depth - 1)
    return envelope_bytes()[:-1] + b',"x":' + extra + b"}"


def test_drt19_depth_4_passes_the_depth_check_and_depth_5_is_rejected_as_too_deep() -> None:
    # Depth 4 is not a schema-valid V1 envelope, but it must fail on shape, not depth.
    assert reject(_nested(4), WireErrorCode.ENVELOPE_SHAPE).code is WireErrorCode.ENVELOPE_SHAPE
    reject(_nested(5), WireErrorCode.TOO_DEEP)


def test_brackets_inside_strings_do_not_count_as_depth() -> None:
    payload = payload_with(result_digest="sha256:" + "0" * 64)
    raw = envelope_bytes(payload)[:-1] + b',"x":"[[[[[[[[{{{{{{{{"}'
    reject(raw, WireErrorCode.ENVELOPE_SHAPE)
    escaped = envelope_bytes()[:-1] + b',"x":"\\"[[[[[[[["}'
    reject(escaped, WireErrorCode.ENVELOPE_SHAPE)


def test_deeply_nested_input_is_rejected_without_recursion_errors() -> None:
    reject(b"[" * 200_000, WireErrorCode.TOO_LARGE)
    reject(b"[" * 10_000, WireErrorCode.TOO_DEEP, max_bytes=1_000_000)
    reject(b'{"a":' * 10_000 + b"1" + b"}" * 10_000, WireErrorCode.TOO_DEEP, max_bytes=1_000_000)


